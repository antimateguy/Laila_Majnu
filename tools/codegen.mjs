// Generates web/src/types/gen.ts and api/app/models/ from schemas/.
// `--check` regenerates in memory and exits 1 if anything committed is stale.
import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { compile } from "json-schema-to-typescript";
import { ROOT, SCHEMA_DIR, loadSchemas } from "./lib/schemas.mjs";

const TS_OUT = join(ROOT, "web", "src", "types", "gen.ts");
const PY_OUT = join(ROOT, "api", "app", "models");
const PYTHON = process.env.PYTHON ?? (process.platform === "win32" ? "api/.venv/Scripts/python.exe" : "api/.venv/bin/python");
const HEADER = "// GENERATED by tools/codegen.mjs from schemas/*.schema.json. Do not edit.\n\n";

// json-schema-to-typescript predates 2020-12 and cannot express conditionals:
// an if/then-only allOf turns every object into an open intersection, and
// prefixItems is ignored. Rewrite both into what it understands; Ajv and the
// API still enforce the originals.
function forTs(node) {
  if (Array.isArray(node)) return node.map(forTs);
  if (node === null || typeof node !== "object") return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k === "allOf" && v.every((s) => Object.keys(s).every((key) => ["if", "then", "description"].includes(key)))) continue;
    if (k === "prefixItems") {
      out.items = forTs(v);
      out.additionalItems = false;
      continue;
    }
    if (k === "items" && "prefixItems" in node) continue;
    out[k] = forTs(v);
  }
  return out;
}

async function generateTs() {
  const schemas = loadSchemas().map(({ file, schema }) => ({ file, schema: forTs(schema) }));
  const byId = new Map(schemas.map(({ schema }) => [schema.$id, schema]));
  // One synthetic root that references every document schema, so each shared
  // definition is emitted exactly once into a single file.
  const root = {
    $id: "https://laila-majnu.invalid/schemas/index.json",
    title: "Contracts",
    type: "object",
    additionalProperties: false,
    properties: Object.fromEntries(
      schemas.filter(({ schema }) => schema.type === "object").map(({ file, schema }) => [file, { $ref: schema.$id }]),
    ),
  };
  const ts = await compile(root, "Contracts", {
    bannerComment: "",
    additionalProperties: false,
    strictIndexSignatures: true,
    ignoreMinAndMaxItems: true,
    format: true,
    $refOptions: {
      resolve: {
        local: {
          order: 1,
          canRead: /^https:\/\/laila-majnu\.invalid\//,
          read: (file) => JSON.stringify(byId.get(file.url.split("#")[0])),
        },
      },
    },
  });
  return HEADER + ts;
}

function generatePy() {
  const work = mkdtempSync(join(tmpdir(), "lm-codegen-"));
  const input = join(work, "schemas");
  const out = join(work, "out");
  mkdirSync(input);
  // Only the schemas themselves; schemas/examples/ must not become models.
  for (const { file } of loadSchemas()) copyFileSync(join(SCHEMA_DIR, file), join(input, file));
  try {
    execFileSync(
      join(ROOT, PYTHON),
      [
        "-m", "datamodel_code_generator",
        "--input", input,
        "--input-file-type", "jsonschema",
        "--output", out,
        "--output-model-type", "pydantic_v2.BaseModel",
        "--target-python-version", "3.12",
        "--extra-fields", "forbid",
        "--field-constraints",
        "--use-standard-collections",
        "--use-union-operator",
        "--use-double-quotes",
        "--use-title-as-name",
        "--collapse-root-models",
        "--enum-field-as-literal", "all",
        "--disable-timestamp",
        "--formatters", "ruff-check", "ruff-format",
        "--custom-file-header", "# GENERATED by tools/codegen.mjs from schemas/*.schema.json. Do not edit.",
      ],
      { cwd: ROOT, stdio: ["ignore", "inherit", "inherit"] },
    );
    const files = {};
    const walk = (dir, rel = "") => {
      for (const ent of readdirSync(dir, { withFileTypes: true })) {
        const p = join(dir, ent.name);
        if (ent.isDirectory()) walk(p, join(rel, ent.name));
        else if (ent.name.endsWith(".py")) files[join(rel, ent.name).replaceAll("\\", "/")] = readFileSync(p, "utf8").replaceAll("\r\n", "\n");
      }
    };
    walk(out);
    return files;
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

const check = process.argv.includes("--check");
const outputs = { [TS_OUT]: await generateTs() };
for (const [rel, text] of Object.entries(generatePy())) outputs[join(PY_OUT, rel)] = text;

let stale = 0;
const pyExisting = existsSync(PY_OUT) ? readdirSync(PY_OUT).filter((f) => f.endsWith(".py")).map((f) => join(PY_OUT, f)) : [];
for (const path of pyExisting) {
  if (path in outputs) continue;
  if (check) {
    console.error(`orphaned: ${path.slice(ROOT.length + 1)}`);
    stale++;
  } else {
    rmSync(path);
    console.log(`removed ${path.slice(ROOT.length + 1)}`);
  }
}
for (const [path, text] of Object.entries(outputs)) {
  const current = existsSync(path) ? readFileSync(path, "utf8").replaceAll("\r\n", "\n") : null;
  if (current === text) continue;
  if (check) {
    console.error(`stale: ${path.slice(ROOT.length + 1)}`);
    stale++;
  } else {
    mkdirSync(join(path, ".."), { recursive: true });
    writeFileSync(path, text);
    console.log(`wrote ${path.slice(ROOT.length + 1)}`);
  }
}
if (check && stale) {
  console.error("Generated code is out of date with schemas/. Run `npm run codegen` and commit the result.");
  process.exit(1);
}
